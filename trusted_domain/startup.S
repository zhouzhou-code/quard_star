/*
 * FreeRTOS RISC-V S-Mode Startup Code (终极修正版)
 */

#include "riscv_encoding.h"

    .section .init
    .globl _start
    .type _start, @function

_start:
    /* --------------------------------------------------------------------
     * 1. 核心寄存器初始化 (gp 和 sp) - 绝不能乱动顺序！
     * -------------------------------------------------------------------- */
    /* 临时关闭汇编器的链接松弛优化 (Relaxation) */
    .option push
    .option norelax
    /* 必须第一时间初始化 gp，否则 C 代码里的全局变量会当场爆炸 */
    la      gp, __global_pointer$
    .option pop

    /* 初始化栈指针 __stack_top */
    la      sp, __stack_top

    /* --------------------------------------------------------------------
     * 2. 设置早期异常处理 (Setup Early Trap Handler)
     * -------------------------------------------------------------------- */
    /* S-Mode 使用 stvec (Supervisor Trap Vector) */
    la      t0, early_trap_handler
    csrw    stvec, t0

    /* --------------------------------------------------------------------
     * 3. 启用 FPU 硬件浮点单元 (Enable FPU)
     * -------------------------------------------------------------------- */
#ifdef __riscv_flen
    /* 开启 S-Mode 下的浮点使用权: sstatus.FS = Initial (01) */
    li      t0, SSTATUS_FS
    csrs    sstatus, t0
    /* 现代标准指令：清零浮点控制和状态寄存器 */
    csrw    fcsr, zero
#endif

    /* --------------------------------------------------------------------
     * 4. 搬运 .data 段 (Copy .data)
     * -------------------------------------------------------------------- */
    la      t0, __data_lma
    la      t1, __data_start
    la      t2, __data_end
    bge     t1, t2, copy_data_done

copy_data_loop:
    ld      t3, 0(t0)      /* RV64 专用 8 字节读取 */
    sd      t3, 0(t1)      /* RV64 专用 8 字节写入 */
    addi    t0, t0, 8
    addi    t1, t1, 8
    blt     t1, t2, copy_data_loop

copy_data_done:

    /* --------------------------------------------------------------------
     * 5. 清零 .bss 段 (Clear .bss)
     * -------------------------------------------------------------------- */
    la      t0, __bss_start
    la      t1, __bss_end
    bge     t0, t1, clear_bss_done

clear_bss_loop:
    sd      zero, 0(t0)    /* 直接用 x0 寄存器快速清零 8 字节 */
    addi    t0, t0, 8
    blt     t0, t1, clear_bss_loop

clear_bss_done:

    /* --------------------------------------------------------------------
     * 6. 初始化 C++ / 扩展 C 运行环境
     * -------------------------------------------------------------------- */
    /* 此时 gp, sp 已经就位，bss 已清零，可以安全调用 C 库的初始化函数了 */
    call    __libc_init_array

    /* --------------------------------------------------------------------
     * 7. 终极一跃：跳入主函数 main
     * -------------------------------------------------------------------- */
    li      a0, 0
    li      a1, 0
    call    main

    /* --------------------------------------------------------------------
     * 8. 保底死循环
     * -------------------------------------------------------------------- */
loop_forever:
    j       loop_forever

/* --------------------------------------------------------------------
 * 早期异常捕获钩子 (Early Trap Handler)
 * -------------------------------------------------------------------- */
    .align 4
early_trap_handler:
    /* 上电初期的崩溃全部卡在这里，可用 GDB 连接查看 mepc/sepc 和 mcause/scause */
    j       early_trap_handler